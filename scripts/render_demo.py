"""Render the real output of scripts/demo.sh as docs/assets/demo.svg (the image at the top of the README).

    python scripts/render_demo.py           run the demo and rewrite the image
    python scripts/render_demo.py --check   run the demo and fail if the committed image differs (used in CI)

The text in the image is whatever scripts/demo.sh printed; this script only wraps, colours and draws it. Standard
library only. Run it with Python 3.13, the version the demo lock was written with: other versions add an INFO
line about the lock's Python version to `mintmap diff`.
"""
import os
import subprocess
import sys
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "assets", "demo.svg")
COLS = 112
CHAR_W, LINE_H, PAD, BAR = 7.82, 19, 18, 34
COLOURS = {"plain": "#c9d1d9", "comment": "#8b949e", "command": "#79c0ff", "minus": "#ff7b72", "plus": "#7ee787",
           "finding": "#e3b341", "bad": "#ff7b72", "good": "#7ee787"}


def demo_output() -> str:
    env = dict(os.environ, PYTHON=sys.executable)
    run = subprocess.run(["bash", os.path.join(ROOT, "scripts", "demo.sh")], capture_output=True, text=True,
                         env=env, timeout=300)
    if run.returncode != 0:
        sys.stderr.write(run.stdout + run.stderr)
        sys.exit("render_demo: scripts/demo.sh failed")
    return run.stdout


def style(line: str) -> str:
    if line.startswith("# "):
        return "comment"
    if line.startswith("$ "):
        return "command"
    if line.startswith("-"):
        return "minus"
    if line.startswith("+"):
        return "plus"
    if line.startswith(("FINGERPRINT_CHANGED", "EVIDENCE_DOWNGRADED")):
        return "finding"
    if line.startswith("exit 0") or line.startswith("demo ok"):
        return "good"
    if line.startswith("exit ") or line.strip() == "12":
        return "bad"
    return "plain"


def wrap(line: str) -> list:
    parts = []
    while len(line) > COLS:
        cut = line.rfind(" ", 0, COLS)
        cut = cut if cut > COLS // 2 else COLS
        parts.append(line[:cut])
        line = "    " + line[cut:].lstrip()
    return parts + [line]


def render(text: str) -> str:
    rows = []
    for raw in text.strip("\n").split("\n"):
        kind = style(raw)
        rows += [(kind, part) for part in wrap(raw)]
    width = round(COLS * CHAR_W + 2 * PAD)
    height = BAR + 2 * PAD + LINE_H * len(rows)
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width}" '
           f'height="{height}" role="img" aria-label="Terminal output of the MintMap demo: mintmap diff exits 12 '
           f'on a pull request that makes a TOTP check ignore its result">',
           "<!-- Generated by scripts/render_demo.py from the real output of scripts/demo.sh. Do not edit. -->",
           f'<rect width="{width}" height="{height}" rx="10" fill="#0d1117"/>',
           f'<rect width="{width}" height="{BAR}" rx="10" fill="#161b22"/>',
           f'<rect y="{BAR - 10}" width="{width}" height="10" fill="#161b22"/>',
           '<circle cx="20" cy="17" r="6" fill="#ff5f56"/><circle cx="40" cy="17" r="6" fill="#ffbd2e"/>'
           '<circle cx="60" cy="17" r="6" fill="#27c93f"/>',
           f'<text x="{width / 2}" y="22" text-anchor="middle" fill="#8b949e" font-size="13" '
           f'font-family="ui-monospace,SFMono-Regular,Menlo,Consolas,Liberation Mono,monospace">'
           f'bash scripts/demo.sh</text>',
           '<g font-size="13" font-family="ui-monospace,SFMono-Regular,Menlo,Consolas,Liberation Mono,monospace" '
           'xml:space="preserve">']
    y = BAR + PAD + 13
    for kind, part in rows:
        if part:
            weight = ' font-weight="bold"' if kind in ("command", "bad", "good") else ""
            out.append(f'<text x="{PAD}" y="{y}" fill="{COLOURS[kind]}"{weight} '
                       f'textLength="{len(part) * CHAR_W:.1f}" lengthAdjust="spacingAndGlyphs">{escape(part)}</text>')
        y += LINE_H
    out += ["</g>", "</svg>", ""]
    return "\n".join(out)


def main(argv) -> int:
    svg = render(demo_output())
    if "--check" in argv:
        with open(OUT, encoding="utf-8") as fh:
            if fh.read() == svg:
                print("docs/assets/demo.svg matches the output of scripts/demo.sh")
                return 0
        print("docs/assets/demo.svg is out of date: run `python scripts/render_demo.py` and commit the result",
              file=sys.stderr)
        return 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(svg)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
